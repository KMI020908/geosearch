"""Per-query-type prompts for the synthetic query generator.

One system prompt per ``sample_source`` instead of one prompt describing every
case at once. Two reasons:

* **Fewer misunderstandings.** A single shared prompt had to say "some requests
  also include a region and/or a country", "the name may list several city
  names" — conditionals the model has to resolve on every call. Each prompt here
  states only its own case, with its own input fields and its own expected
  entity set, so there is nothing to resolve.
* **Prefix caching.** DeepSeek caches request prefixes automatically and bills
  cache hits cheaper. Every instruction that does not vary per request — the
  rules, the style glossary, the JSON contract and its example — lives in the
  *system* message, so the cacheable prefix is as long as possible and the user
  message carries only the handful of variable fields. The generator sends one
  ``sample_source`` group at a time (:mod:`src.dataset.generate`) so those five
  prefixes are not interleaved.

Each spec also declares *which* entities its query type must yield
(``needs_admin1`` / ``needs_country`` / ``multi_city``). The validator in
:mod:`src.dataset.generate` reads those same flags, so the prompt and the check
that enforces it cannot drift apart.

:data:`PROMPT_VERSION` is stamped into every checkpoint row. Bump it whenever a
prompt or the response contract changes: rows generated by an older version are
ignored on warm start and regenerated, instead of being silently mixed into the
dataset. Bump it for a **sampling** change too — ``request_id`` is the plan row's
position, so a changed quota renumbers rows and the warm start would otherwise
attribute finished queries to different plan rows.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from openai.types.chat import ChatCompletionMessageParam

# 3: per-group quotas replaced the old sampling knobs, so every request_id now
# means a different plan row (the prompts themselves are unchanged from 2).
PROMPT_VERSION = 3

# Query-style keys used by the sample plan (`cfg.style_weights`) mapped to the
# instruction the model reads. The whole glossary goes into every system prompt;
# the user message names only the key.
STYLE_INSTRUCTIONS = {
    "search": "Terse browser search input: short, all lowercase, no punctuation.",
    "casual": "Casual and informal, like a chat message.",
    "formal": "One or two complete, grammatically formal sentences.",
    "rich": "A long, multi-sentence passage with rich surrounding context.",
}

_STYLE_GLOSSARY = "\n".join(f"  - {k}: {v}" for k, v in STYLE_INSTRUCTIONS.items())

_COMMON_RULES = f"""
Every request gives you a language code, a style key and a topic.

General rules:
- Write the query entirely in the specified language.
- Write it in the requested style:
{_STYLE_GLOSSARY}
- The topic must shape what the query asks about; do not append it as a keyword.
- A requested name may appear in any natural grammatical form (case, declension,
  preposition) — write it the way a native speaker would in that sentence.
- Never return a bare name as the whole query.
- Invent no place that was not requested.
""".strip()

_ENTITY_RULES = """
Entity rules:
- After writing the query, list every geographic name it contains.
- Copy each span character-for-character out of the query you just wrote, keeping
  its grammatical form: for "отели в Москве" the span is "Москве", not "Москва".
  Never lemmatise, never re-spell, never add or drop a surrounding word.
- List spans in the order they appear in the query.
- Labels: CITY for a populated place; STATE for a US state; REGION for any other
  first-level administrative unit (область, край, province, il); COUNTRY for a
  country.
- Label nothing else — no streets, districts, landmarks, rivers or airports.
""".strip()

_JSON_CONTRACT = """
Answer with json only — no prose, no markdown fences. Exactly these fields:
- "query": string — the generated query.
- "entities": array of objects {"text": <span>, "label": <label>}.
- "confidence": number between 0 and 1 — how sure you are that the query follows
  every rule above: right language, every requested name present, no extra place,
  spans copied exactly. Use 1.0 only when certain; below 0.5 when you had to bend
  a rule.

Example of the json shape (for a different request):
{"query": "отели в Ростове-на-Дону, Ростовская область", "entities": [{"text":
"Ростове-на-Дону", "label": "CITY"}, {"text": "Ростовская область", "label":
"REGION"}], "confidence": 0.95}
""".strip()


def _system_prompt(task: str, query_rules: str, entities: str) -> str:
    """Compose one system prompt out of the task-specific and shared blocks.

    The shared blocks come last and are byte-identical across types; the
    task-specific text comes first because that is what the model should read as
    its job description.
    """
    return "\n\n".join(
        [
            task.strip(),
            _COMMON_RULES,
            f"Query rules for this request type:\n{query_rules.strip()}",
            _ENTITY_RULES,
            f"Entities for this request type:\n{entities.strip()}",
            _JSON_CONTRACT,
        ]
    )


def _line(field: str, value: object) -> str:
    return f"{field}: {value}"


def _one_city_user(row: dict) -> str:
    return "\n".join(
        [
            _line("language", row["isolanguage"]),
            _line("name", row["name"]),
            _line("style", row["style"]),
            _line("topic", row["topic"]),
        ]
    )


def _multi_city_user(row: dict) -> str:
    return "\n".join(
        [
            _line("language", row["isolanguage"]),
            _line("names", row["name"]),
            _line("style", row["style"]),
            _line("topic", row["topic"]),
        ]
    )


def _city_admin1_user(row: dict) -> str:
    return "\n".join(
        [
            _line("language", row["isolanguage"]),
            _line("name", row["name"]),
            _line("region", row["admin1_name"] or ""),
            _line("style", row["style"]),
            _line("topic", row["topic"]),
        ]
    )


def _city_country_user(row: dict) -> str:
    return "\n".join(
        [
            _line("language", row["isolanguage"]),
            _line("name", row["name"]),
            _line("country", row["country_name"] or ""),
            _line("style", row["style"]),
            _line("topic", row["topic"]),
        ]
    )


def _city_admin1_country_user(row: dict) -> str:
    return "\n".join(
        [
            _line("language", row["isolanguage"]),
            _line("name", row["name"]),
            _line("region", row["admin1_name"] or ""),
            _line("country", row["country_name"] or ""),
            _line("style", row["style"]),
            _line("topic", row["topic"]),
        ]
    )


@dataclass(frozen=True)
class PromptSpec:
    """One query type's prompt plus the entity contract it promises.

    ``needs_admin1`` / ``needs_country`` say whether the query *must* name a
    region / a country (and therefore must return exactly one such span); when
    false, naming one is a rule violation. ``multi_city`` switches the expected
    CITY-span count from one to "one per requested name".
    """

    system: str
    build_user: Callable[[dict], str]
    needs_admin1: bool
    needs_country: bool
    multi_city: bool = False


PROMPTS: dict[str, PromptSpec] = {
    "one_city": PromptSpec(
        system=_system_prompt(
            task="""
You write one realistic search query about a single city. The queries train a
geographic search reranker, so they must read like something a real user typed.

You receive: language, name (the city), style, topic.
""",
            query_rules="""
- The query must mention the city exactly once.
- Mention no other place at all: no region, no country, no district, no
  neighbouring city. The query must contain exactly one geographic name.
""",
            entities="exactly one CITY span — the city as written in the query.",
        ),
        build_user=_one_city_user,
        needs_admin1=False,
        needs_country=False,
    ),
    "multi_city": PromptSpec(
        system=_system_prompt(
            task="""
You write one realistic search query that names several cities at once (e.g. a
trip between them, a comparison, a route). The queries train a geographic search
reranker, so they must read like something a real user typed.

You receive: language, names (two or three city names, comma-separated), style,
topic.
""",
            query_rules="""
- Every one of the given names must appear in the query, each exactly once.
- The result must be one natural request about all of them together, not several
  sentences glued side by side.
- Mention no other place: no region, no country, no city that was not listed.
""",
            entities="one CITY span per given name, in the order they appear in "
            "the query.",
        ),
        build_user=_multi_city_user,
        needs_admin1=False,
        needs_country=False,
        multi_city=True,
    ),
    "city_admin1": PromptSpec(
        system=_system_prompt(
            task="""
You write one realistic search query that names a city together with the region
it lies in, so a search engine can tell it apart from cities of the same name
elsewhere. The queries train a geographic search reranker.

You receive: language, name (the city), region, style, topic.
""",
            query_rules="""
- The query must clearly mention both the city and the region.
- The region is given in English. Render it the way a native speaker of the
  target language writes it — translate or transliterate it; never leave an
  English name inside a non-English query (e.g. "Rostov Oblast" ->
  "Ростовская область").
- Do not mention the country or any other place.
""",
            entities="exactly one CITY span and exactly one REGION or STATE span "
            "(STATE only if the region is a US state), both as written in the query.",
        ),
        build_user=_city_admin1_user,
        needs_admin1=True,
        needs_country=False,
    ),
    "city_country": PromptSpec(
        system=_system_prompt(
            task="""
You write one realistic search query that names a city together with its country,
so a search engine can tell it apart from cities of the same name in other
countries. The queries train a geographic search reranker.

You receive: language, name (the city), country, style, topic.
""",
            query_rules="""
- The query must clearly mention both the city and the country.
- The country is already given in the target language — use that spelling,
  inflected naturally if the sentence needs it.
- Do not mention a region, a state, or any other place.
""",
            entities="exactly one CITY span and exactly one COUNTRY span, both as "
            "written in the query.",
        ),
        build_user=_city_country_user,
        needs_admin1=False,
        needs_country=True,
    ),
    "city_admin1_country": PromptSpec(
        system=_system_prompt(
            task="""
You write one realistic search query that names a city together with both its
region and its country — the fully disambiguated form. The queries train a
geographic search reranker.

You receive: language, name (the city), region, country, style, topic.
""",
            query_rules="""
- The query must clearly mention the city, the region and the country.
- The region is given in English. Render it the way a native speaker of the
  target language writes it — translate or transliterate it; never leave an
  English name inside a non-English query (e.g. "Rostov Oblast" ->
  "Ростовская область").
- The country is already given in the target language — use that spelling,
  inflected naturally if the sentence needs it.
- Mention no other place.
""",
            entities="exactly one CITY span, exactly one REGION or STATE span "
            "(STATE only if the region is a US state) and exactly one COUNTRY span, "
            "all as written in the query.",
        ),
        build_user=_city_admin1_country_user,
        needs_admin1=True,
        needs_country=True,
    ),
}


def get_spec(sample_source: str) -> PromptSpec:
    """Return the prompt spec for a plan row's ``sample_source``.

    Raises ``KeyError`` with the known kinds listed: a new row kind added in
    :mod:`src.dataset.sampling` must get its own prompt, never fall back to a
    generic one.
    """
    try:
        return PROMPTS[sample_source]
    except KeyError:
        known = ", ".join(sorted(PROMPTS))
        raise KeyError(
            f"no prompt for sample_source {sample_source!r}; known kinds: {known}. "
            "Add a PromptSpec in src/dataset/prompts.py."
        ) from None


def build_messages(row: dict) -> list[ChatCompletionMessageParam]:
    """Build the chat messages for one generation call.

    The system message is the type's static prompt (the cacheable prefix); the
    user message holds only this row's variable fields.
    """
    spec = get_spec(row["sample_source"])
    return [
        {"role": "system", "content": spec.system},
        {"role": "user", "content": spec.build_user(row)},
    ]
